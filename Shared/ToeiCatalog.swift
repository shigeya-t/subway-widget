import Foundation

enum LineID: String, CaseIterable, Codable, Sendable, Identifiable {
    case asakusa
    case mita
    case shinjuku
    case oedo

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .asakusa: return "浅草線"
        case .mita: return "三田線"
        case .shinjuku: return "新宿線"
        case .oedo: return "大江戸線"
        }
    }

    /// 交通局の路線色。
    var colorHex: String {
        switch self {
        case .asakusa: return "EC6E65"
        case .mita: return "0079C2"
        case .shinjuku: return "B0C124"
        case .oedo: return "B6007A"
        }
    }

    /// Yahoo!路線情報の運行情報 (`/diainfo/{id}/0`)。
    var yahooDiaInfoID: Int {
        switch self {
        case .asakusa: return 128
        case .mita: return 129
        case .shinjuku: return 130
        case .oedo: return 131
        }
    }

    var directionCodes: [String] {
        switch self {
        case .asakusa, .mita: return ["N", "S"]
        case .shinjuku: return ["E", "W"]
        case .oedo: return ["A", "B", "C"]
        }
    }

    func fallbackDirectionLabel(_ code: String) -> String {
        switch (self, code) {
        case (.asakusa, "N"): return "押上・京成線方面"
        case (.asakusa, "S"): return "西馬込・京急線方面"
        case (.mita, "N"): return "西高島平方面"
        case (.mita, "S"): return "目黒方面"
        case (.shinjuku, "E"): return "本八幡方面"
        case (.shinjuku, "W"): return "新宿方面"
        case (.oedo, "A"): return "A方面"
        case (.oedo, "B"): return "B方面"
        case (.oedo, "C"): return "光が丘方面"
        default: return "\(code)方面"
        }
    }
}

/// ウィジェット・メニューバーの選択単位（路線×駅×方面）。
struct SelectionKey: Hashable, Codable, Sendable, Identifiable {
    let line: LineID
    let stationCode: String
    let direction: String

    var id: String { "\(line.rawValue):\(stationCode):\(direction)" }

    static let `default` = SelectionKey(line: .oedo, stationCode: "E17", direction: "B")
}

struct Station: Hashable, Codable, Sendable, Identifiable {
    let line: LineID
    let code: String
    let name: String
    let directions: [String]
    let yahooStationID: Int
    let yahooDirectionIDs: [String: Int]
    let yahooDirectionLabels: [String: String]

    var id: String { "\(line.rawValue):\(code)" }

    /// 駅ナンバリング（`E-17`）。
    var numbering: String {
        "\(code.prefix(1))-\(code.dropFirst())"
    }

    func directionLabel(_ code: String) -> String {
        if let label = yahooDirectionLabels[code], !label.isEmpty {
            return label.hasSuffix("方面") ? label : "\(label)方面"
        }
        return line.fallbackDirectionLabel(code)
    }

    func yahooGroupID(for direction: String) -> Int? {
        yahooDirectionIDs[direction]
    }
}

enum ToeiCatalog {
    static let stations: [Station] = {
        var result: [Station] = []
        result += make(.asakusa, asakusaRows)
        result += make(.mita, mitaRows)
        result += make(.shinjuku, shinjukuRows)
        result += make(.oedo, oedoRows)
        return result
    }()

    static func stations(on line: LineID) -> [Station] {
        stations.filter { $0.line == line }
    }

    static func station(line: LineID, code: String) -> Station? {
        stations.first { $0.line == line && $0.code == code }
    }

    static func station(id: String) -> Station? {
        stations.first { $0.id == id }
    }

    static func selection(from id: String) -> SelectionKey? {
        let parts = id.split(separator: ":").map(String.init)
        guard parts.count == 3, let line = LineID(rawValue: parts[0]) else { return nil }
        let key = SelectionKey(line: line, stationCode: parts[1], direction: parts[2])
        guard let station = station(line: line, code: key.stationCode),
              station.directions.contains(key.direction)
        else { return nil }
        return key
    }

    private static func make(
        _ line: LineID,
        _ rows: [(String, String, [String], Int, [String: Int], [String: String])]
    ) -> [Station] {
        rows.map {
            Station(
                line: line,
                code: $0.0,
                name: $0.1,
                directions: $0.2,
                yahooStationID: $0.3,
                yahooDirectionIDs: $0.4,
                yahooDirectionLabels: $0.5
            )
        }
    }

